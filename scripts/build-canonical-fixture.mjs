// Builds tests/fixtures/canonical-face.json from MediaPipe's canonical face model.
//
// Usage: node scripts/build-canonical-fixture.mjs path/to/canonical_face_model.obj
// Source: https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
//
// The OBJ has 468 vertices in cm with y up and z toward the viewer. We convert
// to MediaPipe image space (x right, y down, z away), scale into a unit square
// the way normalized landmarks would look, and append 10 synthetic iris
// landmarks (468–477) placed around each eye's centre.
import { readFileSync, writeFileSync } from 'node:fs'

const [objPath] = process.argv.slice(2)
if (!objPath) throw new Error('usage: build-canonical-fixture.mjs <canonical_face_model.obj>')

const SCALE = 0.025 // cm → normalized units; face width ≈ 0.38
const CENTER = 0.5
const round = (n) => Math.round(n * 1e6) / 1e6 + 0 // `+ 0` turns -0 into 0

const verts = readFileSync(objPath, 'utf8')
  .split('\n')
  .filter((l) => l.startsWith('v '))
  .map((l) => l.trim().split(/\s+/).slice(1, 4).map(Number))
if (verts.length !== 468) throw new Error(`expected 468 vertices, got ${verts.length}`)

const landmarks = verts.map(([x, y, z]) => ({
  x: round(CENTER + x * SCALE),
  y: round(CENTER - y * SCALE),
  z: round(-z * SCALE),
}))

// Iris: centre + 4 points (right, top, left, bottom) at a ~0.6 cm radius.
const IRIS_RADIUS = 0.6 * SCALE
for (const eye of [
  [33, 133, 159, 145], // subject's right eye → 468–472
  [362, 263, 386, 374], // subject's left eye → 473–477
]) {
  const c = ['x', 'y', 'z'].map((k) => eye.reduce((s, i) => s + landmarks[i][k], 0) / eye.length)
  landmarks.push({ x: round(c[0]), y: round(c[1]), z: round(c[2]) })
  for (const [dx, dy] of [[1, 0], [0, -1], [-1, 0], [0, 1]]) {
    landmarks.push({ x: round(c[0] + dx * IRIS_RADIUS), y: round(c[1] + dy * IRIS_RADIUS), z: round(c[2]) })
  }
}

writeFileSync(
  new URL('../tests/fixtures/canonical-face.json', import.meta.url),
  JSON.stringify(
    {
      description:
        'MediaPipe canonical face model (Apache-2.0) as 478 frontal landmarks in image space. Iris points 468-477 are synthetic. Generated by scripts/build-canonical-fixture.mjs.',
      landmarks,
    },
    null,
    0,
  ).replace(/\},\{/g, '},\n{') + '\n',
)
